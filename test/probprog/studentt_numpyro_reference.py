"""Pointwise NumPyro reference log densities for Impulse's StudentT and
HalfStudentT natives (test/probprog/distributions.jl).

HalfStudentT(df, scale) is the brms/Stan truncated form
    student_t_lpdf(x | df, 0, scale) - student_t_lccdf(0 | df, 0, scale),
which in NumPyro is
    TruncatedDistribution(StudentT(df, 0.0, scale), low=0.0)
(a LeftTruncatedDistribution). Each value is computed by a jax.jit-ed
log_prob with df, loc, scale and x passed as runtime float64 scalars (as a
NumPyro MCMC kernel evaluates it); the jitted values are written as Julia hex
float literals. The eager (op-by-op) value is also computed and every point
where it differs from the jitted one is listed on stderr.

Run (from Reactant.jl):
  PYTHONPATH=/mnt/sbrantq/probprog/jax:/mnt/sbrantq/probprog/numpyro \
  JAX_PLATFORMS=cpu python test/probprog/studentt_numpyro_reference.py \
      > test/probprog/studentt_numpyro_reference_values.jl
"""
import itertools
import sys

import jax
import jax.numpy as jnp

jax.config.update("jax_enable_x64", True)
import numpyro  # noqa: E402
import numpyro.distributions as dist  # noqa: E402
from numpyro.distributions.truncated import LeftTruncatedDistribution  # noqa: E402

DFS = [0.5, 1.0, 2.5, 3.0, 7.0, 30.0, 1000.0]
SCALES = [0.01, 1.0, 10.0, 1000.0]
HALF_XS = [1e-300, 1e-8, 1e-3, 0.5, 1.0, 3.0, 10.0, 123.456, 1e5, 1e10, 1e100]
LOCS = [-8.0, 0.0, 8.0]
T_XS = [-1e10, -123.456, -3.0, -0.5, 0.0, 1e-8, 0.5, 8.0, 10.0, 1e5, 1e100]


def half_lp(df, scale, x):
    d = dist.TruncatedDistribution(dist.StudentT(df, 0.0, scale), low=0.0)
    return d.log_prob(x)


def t_lp(df, loc, scale, x):
    return dist.StudentT(df, loc, scale).log_prob(x)


def f64(v):
    return jnp.asarray(v, dtype=jnp.float64)


def jl(v):
    return float(v).hex()


def main():
    assert isinstance(
        dist.TruncatedDistribution(dist.StudentT(3.0, 0.0, 10.0), low=0.0),
        LeftTruncatedDistribution,
    )
    half_jit = jax.jit(half_lp)
    t_jit = jax.jit(t_lp)
    out = sys.stdout
    eager_diff = []
    out.write("# Generated by studentt_numpyro_reference.py; do not edit.\n")
    out.write(f"# jax {jax.__version__}, numpyro {numpyro.__version__}\n")
    out.write("# (df, scale, x, NumPyro log_prob) as float64 hex literals\n")
    out.write("#! format: off\n")
    out.write("const HALF_STUDENT_T_NUMPYRO_REF = [\n")
    for df, sc, x in itertools.product(DFS, SCALES, HALF_XS):
        lp = half_jit(f64(df), f64(sc), f64(x))
        lpe = half_lp(f64(df), f64(sc), f64(x))
        if float(lp).hex() != float(lpe).hex():
            eager_diff.append(("half", df, sc, x, float(lp).hex(), float(lpe).hex()))
        out.write(f"    ({jl(df)}, {jl(sc)}, {jl(x)}, {jl(lp)}),\n")
    out.write("]\n\n")
    out.write("# (df, loc, scale, x, NumPyro log_prob)\n")
    out.write("const STUDENT_T_NUMPYRO_REF = [\n")
    for df, lc, sc, x in itertools.product(DFS, LOCS, SCALES, T_XS):
        lp = t_jit(f64(df), f64(lc), f64(sc), f64(x))
        lpe = t_lp(f64(df), f64(lc), f64(sc), f64(x))
        if float(lp).hex() != float(lpe).hex():
            eager_diff.append(("t", df, lc, sc, x, float(lp).hex(), float(lpe).hex()))
        out.write(f"    ({jl(df)}, {jl(lc)}, {jl(sc)}, {jl(x)}, {jl(lp)}),\n")
    out.write("]\n")
    # Not asserted: eager dispatch skips jit rewrites, so the last ulp may differ.
    sys.stderr.write(f"jit-vs-eager bit differences: {len(eager_diff)}\n")
    for row in eager_diff:
        sys.stderr.write(f"  {row}\n")


if __name__ == "__main__":
    main()
